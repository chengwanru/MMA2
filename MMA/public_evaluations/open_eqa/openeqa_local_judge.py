"""Local (no-API, no-token-limit) LLM-Match judge using an already-downloaded HF model.

Reuses the exact same mmbench.txt prompt + parse_score() as the API judges in
openeqa_llm_match.py, so scores are directly comparable -- just generated by a
local forward pass instead of a remote call. Meant for Qwen3-VL-2B/8B-Instruct,
already present on disk for the draft/target models in this pipeline; no
download needed.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, List, Optional

from openeqa_llm_match import _load_prompt, parse_score

_MODEL_CACHE: dict = {}


@dataclass(frozen=True)
class LocalJudgeConfig:
    model_path: str
    device: str = "cuda:0"
    max_new_tokens: int = 8
    dtype: str = "bfloat16"


def _load_model(cfg: LocalJudgeConfig):
    key = (cfg.model_path, cfg.device, cfg.dtype)
    if key in _MODEL_CACHE:
        return _MODEL_CACHE[key]

    import torch
    from transformers import AutoModelForImageTextToText, AutoProcessor

    torch_dtype = {"bfloat16": torch.bfloat16, "float16": torch.float16}.get(
        cfg.dtype, "auto"
    )
    print(f"[local_judge] loading {cfg.model_path} on {cfg.device} ({cfg.dtype}) ...", flush=True)
    model = AutoModelForImageTextToText.from_pretrained(
        cfg.model_path,
        torch_dtype=torch_dtype,
        local_files_only=True,
        trust_remote_code=True,
    ).to(cfg.device)
    model.eval()
    processor = AutoProcessor.from_pretrained(
        cfg.model_path, trust_remote_code=True, local_files_only=True
    )
    _MODEL_CACHE[key] = (model, processor)
    print("[local_judge] loaded.", flush=True)
    return model, processor


def get_local_judge_score(
    *,
    question: str,
    answer: str,
    prediction: str,
    extra_answers: Optional[list] = None,
    cfg: LocalJudgeConfig,
    verbose: bool = False,
) -> int:
    if prediction is None:
        return 0

    import torch

    model, processor = _load_model(cfg)
    tokenizer = getattr(processor, "tokenizer", processor)

    prompt_name = "mmbench" if extra_answers is None else "mmbench-extra"
    prompt = _load_prompt(prompt_name)
    content = prompt.format(
        question=question,
        answer=answer,
        prediction=prediction,
        extra_answers=extra_answers,
    )

    messages = [{"role": "user", "content": content}]
    text = processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = tokenizer(text, return_tensors="pt").to(cfg.device)

    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=cfg.max_new_tokens,
            do_sample=False,
            pad_token_id=tokenizer.pad_token_id or tokenizer.eos_token_id,
        )
    new_tokens = out[0][inputs["input_ids"].shape[1] :]
    output = tokenizer.decode(new_tokens, skip_special_tokens=True).strip()
    if verbose:
        print(f"[local_judge/{cfg.model_path}] {output!r}", flush=True)
    return parse_score(output)
